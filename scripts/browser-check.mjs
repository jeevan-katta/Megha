import { chromium } from '@playwright/test';
import fs from 'node:fs';
const web = process.env.WEB_URL || 'http://127.0.0.1:3000';
fs.mkdirSync('.local/screenshots', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(web, { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: 'Shop by Category', exact: true }).waitFor();
await page.screenshot({ path: '.local/screenshots/home-desktop.png', fullPage: true });
await page.getByRole('button', { name: 'Add Pressure Switch to cart', exact: true }).click();
await page.goto(web + '/cart', { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: 'Your Cart (1 Items)' }).waitFor();
await page.screenshot({ path: '.local/screenshots/cart-desktop.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(web, { waitUntil: 'networkidle' });
await page.screenshot({ path: '.local/screenshots/home-mobile.png', fullPage: true });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
console.log(JSON.stringify({ errors, mobileOverflow: overflow, homeTitle: await page.title() }));
await browser.close();
if (errors.length || overflow) process.exit(1);
